--Populate DIM_DATE from 2005-01-01 to 2030-12-31

INSERT INTO dim_date (
    date_key,
    full_date,
    day_number,
    month_number,
    month_name,
    quarter_number,
    year_number
)
SELECT
    TO_NUMBER(TO_CHAR(dt, 'YYYYMMDD')) AS date_key,
    dt AS full_date,
    TO_NUMBER(TO_CHAR(dt, 'DD')) AS day_number,
    TO_NUMBER(TO_CHAR(dt, 'MM')) AS month_number,
    TO_CHAR(dt, 'MONTH') AS month_name,
    TO_NUMBER(TO_CHAR(dt, 'Q')) AS quarter_number,
    TO_NUMBER(TO_CHAR(dt, 'YYYY')) AS year_number
FROM (
    SELECT DATE '2005-01-01' + LEVEL - 1 AS dt
    FROM dual
    CONNECT BY LEVEL <= DATE '2030-12-31' - DATE '2005-01-01' + 1
);
