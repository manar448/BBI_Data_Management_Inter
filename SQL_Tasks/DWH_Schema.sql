CREATE TABLE dim_date (
    date_key       NUMBER(8) NOT NULL,
    full_date      DATE NOT NULL,
    day_number     NUMBER(2),
    month_number   NUMBER(2),
    month_name     VARCHAR2(20),
    quarter_number NUMBER(1),
    year_number    NUMBER(4),

    CONSTRAINT pk_dim_date
        PRIMARY KEY (date_key),

    CONSTRAINT uk_dim_date_full_date
        UNIQUE (full_date)
);
------------------------------------------------------------
CREATE TABLE dim_job (
    hash_job    VARCHAR2(64) NOT NULL,
    job_key     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    job_id      VARCHAR2(10) NOT NULL,
    job_title   VARCHAR2(100),
    min_salary  NUMBER(10,2),
    max_salary  NUMBER(10,2),

    CONSTRAINT pk_dim_job
        PRIMARY KEY (job_key),

    CONSTRAINT uk_dim_job_job_id
        UNIQUE (job_id)
);
------------------------------------------------------------
CREATE TABLE dim_department (
    hash_dep        VARCHAR2(64) NOT NULL,
    department_key  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    department_id   NUMBER NOT NULL,
    department_name VARCHAR2(100),
    manager_id      NUMBER,

    CONSTRAINT pk_dim_department
        PRIMARY KEY (department_key),

    CONSTRAINT uk_dim_department_id
        UNIQUE (department_id)
);
------------------------------------------------------------
CREATE TABLE dim_location (
    hash_loc        VARCHAR2(64) NOT NULL,
    location_key    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    location_id     NUMBER NOT NULL,
    street_address  VARCHAR2(200),
    postal_code     VARCHAR2(20),
    city            VARCHAR2(100),
    state_province  VARCHAR2(100),
    country_id      CHAR(2),
    country_name    VARCHAR2(100),
    region_id       NUMBER,
    region_name     VARCHAR2(100),

    CONSTRAINT pk_dim_location
        PRIMARY KEY (location_key),

    CONSTRAINT uk_dim_location_id
        UNIQUE (location_id)
);
------------------------------------------------------------
CREATE TABLE dim_employee (
    hash_emp      VARCHAR2(64) NOT NULL,
    employee_key  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    employee_id   NUMBER NOT NULL,
    first_name    VARCHAR2(50),
    last_name     VARCHAR2(50),
    full_name     VARCHAR2(101),
    email         VARCHAR2(100),
    phone_number  VARCHAR2(30),
    manager_id    NUMBER,
    hire_date     DATE,

    start_date    DATE NOT NULL,
    end_date      DATE NOT NULL,
    current_flag  CHAR(1) DEFAULT 'Y' NOT NULL,

    CONSTRAINT pk_dim_employee
        PRIMARY KEY (employee_key),

    CONSTRAINT ck_dim_employee_current
        CHECK (current_flag IN ('Y', 'N')),

    CONSTRAINT ck_dim_employee_dates
        CHECK (end_date >= start_date)
);
------------------------------------------------------------
CREATE TABLE fact_employment (
    employment_key  NUMBER GENERATED BY DEFAULT AS IDENTITY,

    employee_key    NUMBER NOT NULL,
    job_key         NUMBER NOT NULL,
    department_key  NUMBER NOT NULL,
    location_key    NUMBER NOT NULL,
    date_key        NUMBER NOT NULL,

    salary          NUMBER(10,2),
    commission_pct  NUMBER(5,2),
    employee_count  NUMBER(1) DEFAULT 1 NOT NULL,

    CONSTRAINT pk_fact_employment
        PRIMARY KEY (employment_key),

    CONSTRAINT fk_fact_employee
        FOREIGN KEY (employee_key)
        REFERENCES dim_employee(employee_key),

    CONSTRAINT fk_fact_job
        FOREIGN KEY (job_key)
        REFERENCES dim_job(job_key),

    CONSTRAINT fk_fact_department
        FOREIGN KEY (department_key)
        REFERENCES dim_department(department_key),

    CONSTRAINT fk_fact_location
        FOREIGN KEY (location_key)
        REFERENCES dim_location(location_key),

    CONSTRAINT fk_fact_date
        FOREIGN KEY (date_key)
        REFERENCES dim_date(date_key)
);
------------------------------------------------------------
CREATE INDEX idx_fact_employee
ON fact_employment(employee_key);

CREATE INDEX idx_fact_job
ON fact_employment(job_key);

CREATE INDEX idx_fact_department
ON fact_employment(department_key);

CREATE INDEX idx_fact_location
ON fact_employment(location_key);

CREATE INDEX idx_fact_date
ON fact_employment(date_key);
